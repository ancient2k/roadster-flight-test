/** Editor text in the current UI language with {name} placeholders. */
export function et(key: EditorKey, vars?: Record<string, string | number>): string {
  const s = EDITOR_MESSAGES[getLocale()]?.[key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}
